#!/usr/bin/env node
/**
 * Installs the local git hooks. Run via `npm run hooks` (and automatically by
 * npm's `prepare` script on install).
 *
 * The hook is a safety net, not a control: it only sees commits made on a
 * machine that ran this. CI runs the same check on every push.
 */
const fs = require("fs");
const path = require("path");

const gitDir = (() => {
  try {
    return require("child_process")
      .execSync("git rev-parse --git-dir", { encoding: "utf8" })
      .trim();
  } catch {
    return null;
  }
})();

if (!gitDir) {
  console.log("install-git-hooks: not a git checkout, skipping.");
  process.exit(0);
}

const hooksDir = path.resolve(gitDir, "hooks");
fs.mkdirSync(hooksDir, { recursive: true });

const hook = path.join(hooksDir, "pre-commit");
const body = `#!/bin/sh
# Generated by scripts/install-git-hooks.js — do not edit by hand.
node scripts/check-secrets.js || {
  echo ""
  echo "Commit blocked by scripts/check-secrets.js."
  echo "If the value is not a secret, adjust the rule or the allowlist."
  exit 1
}
`;

fs.writeFileSync(hook, body, { mode: 0o755 });
console.log("install-git-hooks: installed pre-commit hook at " + path.relative(process.cwd(), hook));
